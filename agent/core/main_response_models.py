"""
Pydantic-модель структурированного ответа MAIN агента.

Используется через `response_format=MainFinalAnswer` в `create_deep_agent`.
Аналогично тому как у subagents работает `SubagentResult`, но для main.

ЗАЧЕМ
─────
Main агент имеет тенденцию переписывать sub'овский ответ своими словами
(дорого + риск дубля + риск обрыва при cap'е). Единственный надёжный
способ это предотвратить — НЕ ДАВАТЬ main писать длинный free-text.
`response_format=MainFinalAnswer` с `max_length=1500` chars на поле `text`
обеспечивает это структурно: модель ОБЯЗАНА положить весь свой финальный
ответ в `text`, и Pydantic валидация физически отрежет если он превысит
1500 chars.

КАК РАБОТАЕТ
────────────
- Main делает обычные tool calls (think_tool, task, python_analysis, ...)
- Когда main готов закончить — он вызывает специальный structured-output
  tool (LangChain автоматически добавляет его при response_format)
- Аргумент tool'а должен соответствовать `MainFinalAnswer` Pydantic схеме
- `max_length=1500` на `text` поле = main НЕ МОЖЕТ выкатить переписку
  sub'овского ответа (тот обычно 3000+ chars)
- api_adapter извлекает `structured_response.text` и `structured_response.
  position`, склеивает с sub'овскими summary в правильном порядке

CASE 1 — main ДЕЛЕГИРОВАЛ через task():
  position='intro' (по умолчанию):  Финал = main.text + "\\n---\\n" + sub.summary(s)
  position='outro':                  Финал = sub.summary(s) + "\\n---\\n" + main.text
  main.text — короткий комментарий: вступление, «следующий шаг», синтез
  и т.д. Не повторяет sub.summary (даже не может, max=1500 chars).

CASE 2 — main отвечает САМ (без task, через sample_table или из system):
  Финал = main.text (position игнорируется — sub.summary'ев нет)
  1500 chars хватает на короткий ответ. Если задача требует длинного
  ответа — нужно делегировать в подагент (тот не ограничен 1500 chars).
"""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


class MainFinalAnswer(BaseModel):
    """Структурированный финальный ответ main агента."""

    text: str = Field(
        default="",
        max_length=1500,
        description=(
            "Текст от main для финального ответа. Лимит 1500 chars (~375 токенов).\n\n"
            "ПОСЛЕ task() делегирования: комментарий поверх ответа подагента. "
            "Старайся ВСЕГДА добавить что-нибудь полезное — даже одна строка "
            "ценится. Что писать:\n"
            "- Вступительный комментарий, постановка задачи, контекст («Принято, "
            "  делегирую запрос», «Смотрю динамику за квартал») — задаёт тон "
            "  перед детальным ответом подагента. Для этого используй "
            "  `position='intro'` (по умолчанию).\n"
            "- Следующий логичный шаг расследования («следующий шаг: проверить "
            "  площадки spam в Нити», «следующий шаг: глянуть динамику ROAS "
            "  по неделям») — обычно `position='outro'`, после данных.\n"
            "- Контекст из истории сессии («это согласуется с тем что мы видели "
            "  в прошлом turn'е», «ROAS падает третью неделю — паттерн») — "
            "  лучше `position='outro'`.\n"
            "- Синтез если несколько подагентов — общая закономерность, "
            "  противоречия, как один результат дополняет другой — `outro`.\n"
            "- Простой акцент на главном — «обрати внимание на campaign X — "
            "  она даёт 60% всех проблем» — `outro`.\n\n"
            "❌ НЕ пиши вводных/связочных фраз, которые ссылаются на «то что "
            "ниже» или «то что выше», если ты не уверен в положении: "
            "«Вот точные диапазоны:», «Смотри таблицу ниже», «Как видно "
            "выше...». Если такая фраза нужна — явно укажи `position` "
            "соответственно (`intro` для «вот ниже...», `outro` для «как "
            "видно выше...»). Лучше всего — пиши самодостаточный контент, "
            "без указателей.\n\n"
            "НЕ повторяй ответ подагента — у тебя 1500 chars, не уместишь "
            "даже сокращённую версию (sub.summary обычно 3000+ chars). И не "
            "переписывай его — он автоматически показывается пользователю "
            "ЦЕЛИКОМ (до или после твоего текста, см. `position`).\n\n"
            "Пиши text='' (пустой) ТОЛЬКО если sub.summary исчерпывающе "
            "ответил И из истории сессии нечего добавить. По умолчанию ХОТЯ "
            "БЫ next-step или акцент должен быть.\n\n"
            "БЕЗ task() (когда отвечаешь сам через sample_table или из system "
            "prompt): полный ответ для пользователя в Markdown, до 1500 chars. "
            "Если требуется длиннее — это сигнал что надо было делегировать."
        ),
    )

    position: Literal["intro", "outro"] = Field(
        default="intro",
        description=(
            "Где показать `text` относительно ответа подагента в финальной "
            "склейке (видит пользователь):\n\n"
            "- `intro` (по умолчанию): text → sub.summary. Используй для "
            "  вступительного комментария — «Принято, делегирую», постановки "
            "  задачи, фраз вида «Вот точные диапазоны:» / «Ниже — детальный "
            "  разбор». Также используй когда text задаёт контекст для "
            "  чтения данных подагента.\n\n"
            "- `outro`: sub.summary → text. Используй для next-step выводов "
            "  («следующий шаг…»), синтеза по нескольким подагентам, акцента "
            "  на главном после данных, фраз вида «Как видно из таблицы…».\n\n"
            "Если main отвечал САМ (без task() делегирования) — position "
            "игнорируется: sub.summary'ев нет, виден только text.\n\n"
            "Правило выбора: посмотри на свой `text` и спроси себя — "
            "«ссылается ли он на данные ниже или комментирует данные выше?» "
            "Ссылается ВНИЗ (вводный/постановочный) → `intro`. Комментирует "
            "ВЕРХ (next-step, синтез, акцент) → `outro`."
        ),
    )
